
# Математические операции

print(3 + 2)  #5
print(3 - 2)  #1
print(3 * 2)  #6
print(3 / 2)  #1.5
print(3 ** 2) #9
print(3 % 2)  #1
print(3 // 2) #1


# Математические

print(type(10))                   #int		 целое число
print(type(3.14))		  #float	 не точное число
print(type(1 + 3j))		  #complex	 комплексное число
print(type('Asabeneh'))		  #string	 строка,текст
print(type([1, 2, 3])) 		  #list		 список
print(type({'name': 'Asabeneh'})) #dictionary	 словарь
print(type({9.8, 3.14, 2.7}))	  #set		 множество, коллекция
print(type((9.8, 3.14, 2.7)))	  #tuple	 элементы не изменны
print(type(3 == 3))		  #bool		 результат сравнение
print(type(3 >= 3))		  #bool		 проверка условия
